public class MultilineComment {
    /*
        这是main方法(多行注释)
     */
    public static void main(String[] args) {
        // 定义变量num(单行注释)
        int num = 1;

        /*
            控制台输出num(多行注释)
         */
        System.out.println(num);

        //  /*/**/*/(不支持多行注释嵌套)
    }
}
