public class SingleLineComments {
    // 这是main方法(单行注释)
    public static void main(String[] args) {
        // 控制台输出hello(单行注释)
        System.out.println("hello");

        // 控制台输出world(单行注释)
        System.out.println("world");

        // // 单行注释作用于单行，可以嵌套//,但是没有意义
    }
}
